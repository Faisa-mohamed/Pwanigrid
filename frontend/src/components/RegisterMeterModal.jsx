import { useState } from "react";
import { Copy, CheckCircle2 } from "lucide-react";
import Modal from "./Modal";
import { registerMeter } from "../api/meters";
import { errorMessage } from "../api/client";
import { useToast } from "../context/ToastContext";

export default function RegisterMeterModal({ onClose, onCreated }) {
  const toast = useToast();
  const [name, setName] = useState("");
  const [location, setLocation] = useState("");
  const [errors, setErrors] = useState({});
  const [serverError, setServerError] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [created, setCreated] = useState(null); // the meter returned by the server

  const validate = () => {
    const e = {};
    if (name.trim().length < 2 || name.trim().length > 80) e.name = "Name must be 2 to 80 characters.";
    if (location.length > 120) e.location = "Location can be at most 120 characters.";
    setErrors(e);
    return Object.keys(e).length === 0;
  };

  const submit = async (ev) => {
    ev.preventDefault();
    setServerError("");
    if (!validate()) return;
    setSubmitting(true);
    try {
      const meter = await registerMeter(name.trim(), location.trim());
      setCreated(meter); // we show the ID the BACKEND generated
      onCreated();
      toast.success("Meter registered.");
    } catch (err) {
      setServerError(errorMessage(err));
    } finally {
      setSubmitting(false);
    }
  };

  const copyId = async () => {
    try {
      await navigator.clipboard.writeText(created.meterId);
      toast.success("Meter ID copied.");
    } catch {
      toast.error("Could not copy. Select the ID and copy it manually.");
    }
  };

  if (created) {
    return (
      <Modal title="Meter registered" onClose={onClose}>
        <div className="success-box">
          <CheckCircle2 size={28} />
          <div>The server generated this meter ID:</div>
          <div className="big-id">{created.meterId}</div>
          <button className="btn btn-secondary btn-sm" onClick={copyId}>
            <Copy size={14} /> Copy ID
          </button>
          <p className="muted">Put this exact ID in the ESP32 firmware (METER_ID) for this meter.</p>
        </div>
        <div className="modal-actions">
          <button className="btn btn-primary" onClick={onClose}>
            Done
          </button>
        </div>
      </Modal>
    );
  }

  return (
    <Modal title="Register a meter" onClose={onClose}>
      <form onSubmit={submit} noValidate>
        <div className="field">
          <label htmlFor="m-name">Meter name</label>
          <input id="m-name" value={name} onChange={(e) => setName(e.target.value)} placeholder="e.g. Mama Fatuma's shop" autoFocus />
          {errors.name && <span className="field-error">{errors.name}</span>}
        </div>
        <div className="field">
          <label htmlFor="m-loc">Location (optional)</label>
          <input id="m-loc" value={location} onChange={(e) => setLocation(e.target.value)} placeholder="e.g. Lamu Island" />
          {errors.location && <span className="field-error">{errors.location}</span>}
        </div>
        <p className="muted">The meter ID is generated by the server after you submit.</p>
        {serverError && <div className="alert alert-error">{serverError}</div>}
        <div className="modal-actions">
          <button type="button" className="btn btn-secondary" onClick={onClose} disabled={submitting}>
            Cancel
          </button>
          <button type="submit" className="btn btn-primary" disabled={submitting}>
            {submitting ? "Registering…" : "Register meter"}
          </button>
        </div>
      </form>
    </Modal>
  );
}
